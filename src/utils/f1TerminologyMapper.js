// Helper function to transform text using F1 terminology
export const transformToF1Terminology = (text, category = 'all') => {
    if (!text || typeof text !== 'string') return text

    let transformedText = text

    // Apply transformations based on category
    const categoriesToApply = category === 'all' ?
        Object.keys(F1_TERMINOLOGY) :
        [category]

    categoriesToApply.forEach(cat => {
        if (F1_TERMINOLOGY[cat]) {
            Object.entries(F1_TERMINOLOGY[cat]).forEach(([original, f1Term]) => {
                // Case-insensitive replacement while preserving original case
                const regex = new RegExp(`\\b${original.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi')
                transformedText = transformedText.replace(regex, (match) => {
                    // Preserve case: if original is uppercase, make replacement uppercase
                    if (match === match.toUpperCase()) {
                        return f1Term.toUpperCase()
                    } else if (match[0] === match[0].toUpperCase()) {
                        return f1Term.charAt(0).toUpperCase() + f1Term.slice(1)
                    }
                    return f1Term
                })
            })
        }
    })

    return transformedText
}

// Specific transformation functions for different contexts
